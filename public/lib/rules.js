export function mbtiReason(a, b) {
  const diff = [0, 1, 2, 3].filter((i) => a[i] !== b[i]);
  const sameMid = a[1] === b[1] && a[2] === b[2];
  if (diff.length === 0) return '거울 같은 사이. 이해는 쉽지만 단점도 닮았어요';
  if (sameMid && diff.length === 2 && diff.includes(0) && diff.includes(3)) return `골든 페어: ${a[1]}·${a[2]}는 같고 E/I·J/P는 반대라 ${DOM[a]}·${DOM[b]} 주기능을 안팎으로 나눠 가진 짝`;
  if (a[1] === b[1] && diff.length === 3) return `세상을 보는 눈(${a[1]})은 같은데 나머지는 정반대라 서로 끌리고 보완돼요`;
  if (diff.length === 4) return '정반대 성향. 끌릴 순 있지만 부딪힐 때가 많아요';
  if (a[1] !== b[1]) {
    const nf = (a[1] === 'N' && a[2] === 'F') || (b[1] === 'N' && b[2] === 'F');
    return nf ? '직관·감정(NF)과 감각(S)은 중요하게 여기는 게 달라 오해가 잦아요' : '관심사와 속도가 달라 보통 수준. 역할을 나누면 괜찮아요';
  }
  return `${a[1]} 성향이 같아 대화 결이 맞아요`;
}

